#!/usr/bin/env python3
"""
Bundle the web page into a C header for the firmware.

web/index.html loads web/game.js with a <script src> tag so the page works
from disk. The firmware serves a single gzip-compressed file, so this script
inlines game.js, gzips the result (deterministically) and writes it as a byte
array to firmware/main/web_page.h.

    tools/build_web.py           regenerate the header
    tools/build_web.py --check   exit 1 if the header is out of date (CI)
"""
import gzip
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
HTML = ROOT / "web" / "index.html"
JS = ROOT / "web" / "game.js"
OUT = ROOT / "firmware" / "main" / "web_page.h"


def bundle() -> bytes:
    html = HTML.read_text(encoding="utf-8")
    js = JS.read_text(encoding="utf-8")
    if "</script" in js.lower():
        sys.exit("game.js must not contain '</script'")
    html, count = re.subn(r'<script src="game\.js"></script>',
                          lambda _: "<script>\n" + js + "\n</script>", html, count=1)
    if count != 1:
        sys.exit('index.html must load game.js exactly once with <script src="game.js"></script>')
    return html.encode("utf-8")


def header(raw: bytes) -> str:
    gz = gzip.compress(raw, compresslevel=9, mtime=0)
    lines = []
    for i in range(0, len(gz), 16):
        lines.append("    " + ", ".join("0x%02x" % b for b in gz[i:i + 16]) + ",")
    return (
        "/* Generated by tools/build_web.py from web/index.html and web/game.js.\n"
        " * Do not edit; run the script again after changing the page.\n"
        " * %d bytes of HTML, %d bytes gzipped. */\n"
        "#pragma once\n"
        "#include <stdint.h>\n\n"
        "#define WEB_INDEX_GZ_LEN %du\n\n"
        "static const uint8_t WEB_INDEX_GZ[WEB_INDEX_GZ_LEN] = {\n%s\n};\n"
    ) % (len(raw), len(gz), len(gz), "\n".join(lines))


def embedded_html(text: str) -> bytes:
    """The HTML currently embedded in the header, decompressed."""
    body = text[text.index("{") + 1:text.rindex("}")]
    gz = bytes(int(h, 16) for h in re.findall(r"0x([0-9a-fA-F]{2})", body))
    return gzip.decompress(gz)


def main() -> None:
    raw = bundle()
    if "--check" in sys.argv[1:]:
        # Compare the decompressed page: gzip output differs between zlib
        # versions, so comparing the bytes would fail on another machine.
        try:
            current = embedded_html(OUT.read_text(encoding="utf-8"))
        except (OSError, ValueError) as err:
            sys.exit("%s cannot be read (%s): run tools/build_web.py" % (OUT.relative_to(ROOT), err))
        if current != raw:
            sys.exit("%s is out of date: run tools/build_web.py" % OUT.relative_to(ROOT))
        print("%s is up to date" % OUT.relative_to(ROOT))
        return
    OUT.write_text(header(raw), encoding="utf-8")
    print("wrote %s" % OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
